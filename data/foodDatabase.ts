export function searchFoods(query: string): FoodItem[] {
    const lowerQuery = query.toLowerCase();
    return FOOD_DATABASE.filter(food =>
        food.name.toLowerCase().includes(lowerQuery) ||
        food.brand?.toLowerCase().includes(lowerQuery)
    );
}

export function getFoodsByCategory(category: FoodItem['category']): FoodItem[] {
    return FOOD_DATABASE.filter(food => food.category === category);
}

export function getCategoryDisplayName(category: FoodItem['category']): string {
    const names: Record<FoodItem['category'], string> = {
        protein: 'Proteínas',
        carbs: 'Carbohidratos',
        fats: 'Grasas',
        vegetables: 'Vegetales',
        dairy: 'Lácteos',
        fruits: 'Frutas',
        snacks: 'Snacks',
        beverages: 'Bebidas',
    };
    return names[category];
}

// Get all foods including custom foods
export function getAllFoods(): FoodItem[] {
    const customFoods = useCustomFoodsStore.getState().customFoods;
    return [...FOOD_DATABASE, ...customFoods];
}
